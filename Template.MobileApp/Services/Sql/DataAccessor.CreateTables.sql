CREATE TABLE Data (
    Id INTEGER NOT NULL,
    Name TEXT NOT NULL,
    CreateAt INTEGER NOT NULL,
    PRIMARY KEY (Id)
);

CREATE TABLE BulkData (
    Key1 TEXT NOT NULL,
    Key2 TEXT NOT NULL,
    Key3 TEXT NOT NULL,
    Value1 INTEGER NOT NULL,
    Value2 INTEGER NOT NULL,
    Value3 INTEGER NOT NULL,
    Value4 INTEGER NOT NULL,
    Value5 INTEGER NOT NULL,
    PRIMARY KEY (Key1, Key2, Key3)
);

CREATE TABLE Work (
    Id INTEGER NOT NULL,
    Name TEXT NOT NULL,
    PRIMARY KEY (Id)
);

CREATE TABLE Store (
    Id INTEGER NOT NULL,
    Name TEXT NOT NULL,
    Category INTEGER NOT NULL,
    Area TEXT NOT NULL,
    PointRate INTEGER NOT NULL,
    PRIMARY KEY (Id)
);

CREATE TABLE Notice (
    Id INTEGER NOT NULL,
    Category INTEGER NOT NULL,
    Title TEXT NOT NULL,
    Body TEXT NOT NULL,
    PublishedAt INTEGER NOT NULL,
    IsRead INTEGER NOT NULL,
    PRIMARY KEY (Id)
);

CREATE TABLE History (
    Id INTEGER NOT NULL,
    Kind INTEGER NOT NULL,
    Title TEXT NOT NULL,
    Amount INTEGER NOT NULL,
    OccurredAt INTEGER NOT NULL,
    PRIMARY KEY (Id)
)
